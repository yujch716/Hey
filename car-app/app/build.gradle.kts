// The MacBook's LAN IP for the "local" build (a real head unit or phone on the same Wi-Fi).
// Set nawa.devHost=192.168.x.x in car-app/local.properties (not committed).
val localProperties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}
val devHost: String = localProperties.getProperty("nawa.devHost") ?: "192.168.0.10"

// Release signing: a keystore kept outside the repo, its path and passwords in local.properties (not committed).
//   hey.release.storeFile=/Users/you/.android-keystores/hey-release.jks
//   hey.release.storePassword=… / hey.release.keyAlias=hey / hey.release.keyPassword=…
val releaseStoreFile: String? = localProperties.getProperty("hey.release.storeFile")

/** Plain-HTTP allowance for one dev host, written at configuration time for the "local" build. */
fun cleartextConfigFor(host: String) = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/build.gradle.kts for the "local" build: plain HTTP only to the dev machine -->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">$host</domain>
        <!-- Kakao map script (t1.kakaocdn.net) and tiles (daumcdn.net), requested over http by an http dev page -->
        <domain includeSubdomains="true">daumcdn.net</domain>
        <domain includeSubdomains="true">kakao.com</domain>
        <domain includeSubdomains="true">kakaocdn.net</domain>
    </domain-config>
</network-security-config>
"""
val localResDir = layout.buildDirectory.dir("generated/nsc/local/res").get().asFile
localResDir.resolve("xml").apply { mkdirs() }.resolve("network_security_config.xml").writeText(cleartextConfigFor(devHost))

