            buildConfigField("String", "WEB_BASE_URL", "\"http://10.0.2.2:5173\"")
        }
        create("local") {
            initWith(getByName("debug"))
            matchingFallbacks += "debug"
            buildConfigField("String", "SERVER_URL", "\"http://$devHost:3000\"")
            buildConfigField("String", "WEB_BASE_URL", "\"http://$devHost:5173\"")
        }
        release {
            optimization {
                enable = false
            }
            // 1st contest submission: runs on the Pleos emulator against the MacBook's server and web (10.0.2.2),
            // so src/release allows plain HTTP to that host. Switch to the deployed HTTPS addresses later.
            buildConfigField("String", "SERVER_URL", "\"http://10.0.2.2:3000\"")
            buildConfigField("String", "WEB_BASE_URL", "\"http://10.0.2.2:5173\"")
            // The emulator's navi car never moves, so the real mode has nothing to show: start in demo mode
            buildConfigField("boolean", "DEMO_BY_DEFAULT", "true")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }
    sourceSets.getByName("local").res.srcDir(localResDir)
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
