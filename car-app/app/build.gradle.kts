                storeFile = file(releaseStoreFile)
                storePassword = localProperties.getProperty("hey.release.storePassword")
                keyAlias = localProperties.getProperty("hey.release.keyAlias")
                keyPassword = localProperties.getProperty("hey.release.keyPassword")
            }
